"""
orthoswift_post.report
======================

Client-ready PDF generation for inspection and agriculture jobs.

Uses ReportLab (https://www.reportlab.com/docs/reportlab-userguide.pdf),
which is the long-standing Python PDF library used by countless commercial
GIS reporting stacks. Pure-Python, no external service required.

Design:
* One-page summary by default. A second page is added if there are >5
  flagged zones or >5 stockpiles/hotspots.
* All numbers come from the analytics layer. No fabricated values.
* Conservative language ("candidate", "estimated", "review suggested")
  per the product brief.
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.lib import colors
from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Image,
                                Table, TableStyle)
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

# Register bundled OrthoSWIFT brand fonts when available.
font_dir = Path(__file__).parent.parent / "assets" / "fonts"
font_path = font_dir / "SpaceGrotesk-Bold.ttf"
inter_path = font_dir / "InterVariable.ttf"

USE_SPACE_GROTESK = False
if font_path.exists():
    try:
        pdfmetrics.registerFont(TTFont("SpaceGrotesk", str(font_path)))
        USE_SPACE_GROTESK = True
    except Exception:
        pass

USE_INTER = False
if inter_path.exists():
    try:
        pdfmetrics.registerFont(TTFont("Inter", str(inter_path)))
        USE_INTER = True
    except Exception:
        pass


def _styles():
    s = getSampleStyleSheet()
    
    title_font = "SpaceGrotesk" if USE_SPACE_GROTESK else "Helvetica-Bold"
    body_font = "Inter" if USE_INTER else "Helvetica"
    
    s["Normal"].fontName = body_font
    s["BodyText"].fontName = body_font
    s["Heading1"].fontName = title_font
    s["Heading2"].fontName = title_font
    
    s.add(ParagraphStyle(name="Small", parent=s["BodyText"], fontName=body_font, fontSize=8,
                         leading=10, textColor=colors.grey))
    s.add(ParagraphStyle(name="H1", parent=s["Heading1"], fontName=title_font, fontSize=18,
                         leading=22))
    s.add(ParagraphStyle(name="H2", parent=s["Heading2"], fontName=title_font, fontSize=12,
                         leading=15))
    return s


def _table(data, col_widths=None):
    t = Table(data, colWidths=col_widths, hAlign="LEFT")
    font_name = "Inter" if USE_INTER else "Helvetica"
    header_font = "SpaceGrotesk" if USE_SPACE_GROTESK else "Helvetica-Bold"
    
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f3a5f")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), header_font),
        ("FONTNAME", (0, 1), (-1, -1), font_name),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
         [colors.whitesmoke, colors.white]),
        ("ALIGN", (1, 1), (-1, -1), "RIGHT"),
    ]))
    return t


def _draw_footer(canvas_obj, doc):
    canvas_obj.saveState()
    canvas_obj.setFont("Helvetica-Oblique", 8)
    canvas_obj.setFillColor(colors.HexColor("#666666"))
    
    footer_text = "Generated by OrthoSWIFT | www.orthoswift.net"
    width, height = doc.pagesize
    footer_width = canvas_obj.stringWidth(footer_text, "Helvetica-Oblique", 8)
    footer_x = (width - footer_width) / 2
    canvas_obj.drawString(footer_x, 10 * mm, footer_text)
    canvas_obj.restoreState()


